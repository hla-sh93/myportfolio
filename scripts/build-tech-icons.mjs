/**
 * Generates src/content/tech-icons.ts — the marks shown for each tool on a
 * project page.
 *
 * simple-icons is a build-time dependency only: the paths are copied into a
 * source file so the site ships no icon package and makes no request for a
 * logo. Install it when you need to regenerate:
 *
 *   npm install --no-save simple-icons
 *   node scripts/build-tech-icons.mjs > src/content/tech-icons.ts
 *
 * Adobe withdrew its marks from simple-icons over trademark. Their own app
 * icons are a rounded square holding a two-letter monogram, so the monogram
 * is both the recognisable form and the one that reproduces no artwork.
 */
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const si = require("simple-icons");

/** tool name as stored in data/projects.json → simple-icons slug */
const GLYPH = {
  HTML: "html5",
  CSS: "css",
  JavaScript: "javascript",
  React: "react",
  "Next.js": "nextdotjs",
  MUI: "mui",
  Figma: "figma",
  GSAP: "greensock",
};

/** tools drawn as their own monogram instead */
const MONO = {
  Photoshop: "Ps",
  Illustrator: "Ai",
  "After Effects": "Ae",
  "Premiere Pro": "Pr",
  "Adobe XD": "Xd",
  Lenis: "Ln",
};

const entries = [];
for (const [name, slug] of Object.entries(GLYPH)) {
  const icon = si["si" + slug.charAt(0).toUpperCase() + slug.slice(1)];
  if (!icon) throw new Error(`simple-icons has no "${slug}" (for ${name})`);
  entries.push(`  ${JSON.stringify(name)}: { path: ${JSON.stringify(icon.path)} },`);
}
for (const [name, mono] of Object.entries(MONO)) {
  entries.push(`  ${JSON.stringify(name)}: { mono: ${JSON.stringify(mono)} },`);
}

process.stdout.write(`/**
 * Marks for the tools listed on a project.
 *
 * The names are the ones stored in each project's \`tools\` array, so a tool
 * with no entry here still renders — it falls back to its own initials.
 *
 * Paths come from simple-icons (CC0) and are inlined rather than fetched, so
 * a badge costs no request and inherits its colour from the text around it.
 * Generated by scripts/build-tech-icons.mjs; edit that, not this.
 */

export type TechMark = { path?: string; mono?: string };

export const TECH_MARKS: Record<string, TechMark> = {
${entries.join("\n")}
};

/** "Premiere Pro" → "PP"; the fallback when a tool has no mark above. */
export function initialsOf(name: string): string {
  const words = name.replace(/[^\\p{L}\\p{N} .]/gu, " ").trim().split(/[\\s.]+/).filter(Boolean);
  if (words.length === 1) return words[0].slice(0, 2);
  return words.slice(0, 2).map((w) => w[0]).join("");
}
`);
